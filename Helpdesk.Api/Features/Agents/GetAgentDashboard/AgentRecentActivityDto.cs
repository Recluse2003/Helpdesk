using Helpdesk.Api.Domain.Entities;
using Helpdesk.Api.Domain.Enums;

namespace Helpdesk.Api.Features.Agents.GetAgentDashboard
{
    /// <summary>
    /// Represents a recent activity related to the agent's assigned tickets. 
    /// </summary>
    /// <param name="TicketId">The unique identifier of the <see cref="Ticket"/> the recent activity is from.</param>
    /// <param name="TicketTitle">The title of the <see cref="Ticket"/> the recent activity is from.</param>
    /// <param name="EventType">The type of event or change recorded by the activity.</param>
    /// <param name="Details">Optional additional information describing the activity..</param>
    /// <param name="CreatedAt">The date and time that the activity occured at.</param>
    /// <param name="ActorUserId">The unique identifier of the user who performed the activity, or null if the activity was 
    /// generated by the system.</param>
    /// <param name="ActorDisplayName">The display name of the user who performed the activity, or null if the actor could not be 
    /// identified.</param>
    /// <param name="TargetUserId">The unique identifier of the user targeted by the activity, or null if no specific user 
    /// was targeted.</param>
    /// <param name="TargetDisplayName">The display name of the targeted user, or null if no user was targeted or the user could not
    /// be identified.</param>
    public record AgentRecentActivityDto(
        Guid TicketId,
        string TicketTitle,
        TicketActivityType EventType,
        string? Details,
        DateTime CreatedAt,
        Guid? ActorUserId,
        string? ActorDisplayName,
        Guid? TargetUserId,
        string? TargetDisplayName
    );
}
