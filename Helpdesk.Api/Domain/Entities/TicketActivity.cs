using Helpdesk.Api.Domain.Enums;
using Helpdesk.Api.Domain.Exceptions;

namespace Helpdesk.Api.Domain.Entities
{
    /// <summary>
    /// Represents an activity, recording an event or change associated with a specified support ticket.
    /// </summary>
    public class TicketActivity
    {
        /// <summary>
        /// Gets the unique identifier of the activity.
        /// </summary>
        public Guid Id { get; private set; }

        /// <summary>
        /// Gets the type of event recorded by the activity.
        /// </summary>
        public TicketActivityType ActivityType { get; private set; }

        /// <summary>
        /// Gets a value indicating whether the activity is visible to the ticket customer.
        /// </summary>
        public bool IsPublic { get; private set; }

        /// <summary>
        /// Gets the optional details describing the activity.
        /// </summary>
        public string? Details { get; private set; }

        /// <summary>
        /// Gets the unique identifier of the ticket associated with the activity.
        /// </summary>
        public Guid TicketId { get; private set; }

        /// <summary>
        /// Gets the unique identifier of the user who performed the activity,
        /// or null if the activity was generated by the system.
        /// </summary>
        public Guid? ActorUserId { get; private set; }

        /// <summary>
        /// Gets the date and time the activity was created.
        /// </summary>
        public DateTime CreatedAt { get; private set; }

        /// <summary>
        /// Creates a new activity associated with a specified support ticket.
        /// </summary>
        /// <param name="ticketId">The unique identifier of the associated ticket.</param>
        /// <param name="eventType">The type of activity being recorded.</param>
        /// <param name="actorUserId">The unique identifier of the user performing the activity.</param>
        /// <param name="details">Optional details describing the activity.</param>
        /// <param name="isPublic">Indicates whether the activity is visible to the ticket customer. Defaults to true.</param>
        /// <exception cref="DomainException">
        /// Thrown when the ticket or actor identifier is invalid, or when the activity details exceed 1000 characters.
        /// </exception>
        public TicketActivity(Guid ticketId, TicketActivityType eventType, Guid? actorUserId, string? details = null, bool isPublic = true)
        {
            if (details != null && details.Length > 1000)
                throw new DomainException("A ticket activity's details cannot exceed 1000 characters.");

            if (ticketId == Guid.Empty)
                throw new DomainException("A ticket must be specified.");

            if (actorUserId == Guid.Empty)
                throw new DomainException("A valid activity actor must be specified.");

            Id = Guid.NewGuid();
            ActivityType = eventType;
            IsPublic = isPublic;
            Details = details;
            TicketId = ticketId;
            ActorUserId = actorUserId;
            CreatedAt = DateTime.UtcNow;
        }
    }
}
